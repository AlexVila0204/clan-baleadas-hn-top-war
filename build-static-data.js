// ============================================
// BUILD STATIC DATA — Fetches Clash Royale API data
// Supports two modes:
//   1. LOCAL: Uses hardcoded API_TOKEN (when running from your PC)
//   2. CI/GitHub Actions: Dynamically creates an API Key via Supercell dev portal login
// ============================================

const fs = require('fs');
const path = require('path');

const CLAN_TAG = '%23LCY8L80V';
const API_BASE = 'https://api.clashroyale.com/v1';
const DEV_PORTAL = 'https://developer.clashroyale.com/api';

// Local fallback token (for running from your PC with whitelisted IP)
const LOCAL_API_TOKEN = process.env.CR_API_TOKEN || '';

// Supercell dev portal credentials (for GitHub Actions dynamic key creation)
const SC_EMAIL = process.env.SC_EMAIL || '';
const SC_PASSWORD = process.env.SC_PASSWORD || '';

const dataDir = path.join(__dirname, 'public', 'data');
if (!fs.existsSync(dataDir)) {
  fs.mkdirSync(dataDir, { recursive: true });
}

// ---- Get public IP of this machine/runner ----
async function getPublicIP() {
  const res = await fetch('https://api.ipify.org?format=json');
  const data = await res.json();
  return data.ip;
}

// ---- Supercell Dev Portal: Login and create temporary API Key ----
async function getTokenViaDeveloperPortal(ip) {
  console.log(`Creating temporary API key for IP: ${ip}`);

  // Step 1: Login to dev portal
  const loginRes = await fetch(`${DEV_PORTAL}/login`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ email: SC_EMAIL, password: SC_PASSWORD })
  });

  if (!loginRes.ok) {
    throw new Error(`Supercell login failed (${loginRes.status}). Check SC_EMAIL and SC_PASSWORD.`);
  }

  // Extract session cookie
  const cookies = loginRes.headers.getSetCookie?.() || [];
  const sessionCookie = cookies.find(c => c.startsWith('session='));
  
  // Also try raw headers for older Node versions
  let cookieHeader = '';
  if (sessionCookie) {
    cookieHeader = sessionCookie.split(';')[0];
  } else {
    const rawCookies = loginRes.headers.get('set-cookie') || '';
    const match = rawCookies.match(/session=[^;]+/);
    if (match) cookieHeader = match[0];
  }

  if (!cookieHeader) {
    throw new Error('Could not extract session cookie from Supercell login');
  }

  const portalHeaders = {
    'Content-Type': 'application/json',
    'Cookie': cookieHeader
  };

  // Step 2: List existing keys
  const listRes = await fetch(`${DEV_PORTAL}/apikey/list`, {
    method: 'POST',
    headers: portalHeaders,
    body: JSON.stringify({})
  });
  const listData = await listRes.json();
  const existingKeys = listData.keys || [];

  // Step 3: Check if we already have a key for this IP, or clean up old CI keys
  const CI_KEY_PREFIX = 'gh-actions-';
  
  // Revoke old CI-generated keys to stay within limits (max 10 keys)
  for (const key of existingKeys) {
    if (key.name && key.name.startsWith(CI_KEY_PREFIX)) {
      console.log(`  Revoking old CI key: ${key.name}`);
      await fetch(`${DEV_PORTAL}/apikey/revoke`, {
        method: 'POST',
        headers: portalHeaders,
        body: JSON.stringify({ id: key.id })
      });
    }
  }

  // Step 4: Create new key for current IP
  const keyName = `${CI_KEY_PREFIX}${Date.now()}`;
  const createRes = await fetch(`${DEV_PORTAL}/apikey/create`, {
    method: 'POST',
    headers: portalHeaders,
    body: JSON.stringify({
      name: keyName,
      description: 'Auto-generated by GitHub Actions for Baleadas war stats',
      cidrRanges: [ip],
      scopes: ['royale']
    })
  });

  if (!createRes.ok) {
    const err = await createRes.text();
    throw new Error(`Failed to create API key: ${err}`);
  }

  const createData = await createRes.json();
  const token = createData.key?.key;

  if (!token) {
    throw new Error('API key creation returned no token');
  }

  console.log(`  Created temporary API key: ${keyName}`);
  return token;
}

// ---- Obtain API Token (local or CI) ----
async function getApiToken() {
  // If a token is provided directly (local mode), use it
  if (LOCAL_API_TOKEN) {
    console.log('Using provided CR_API_TOKEN (local mode)');
    return LOCAL_API_TOKEN;
  }

  // If Supercell credentials are available (CI mode), create a dynamic key
  if (SC_EMAIL && SC_PASSWORD) {
    const ip = await getPublicIP();
    console.log(`Runner public IP: ${ip}`);
    return await getTokenViaDeveloperPortal(ip);
  }

  throw new Error(
    'No API credentials found. Set either:\n' +
    '  - CR_API_TOKEN (for local use with whitelisted IP)\n' +
    '  - SC_EMAIL + SC_PASSWORD (for GitHub Actions dynamic key creation)'
  );
}

// ---- Fetch and Save Data ----
async function fetchAndSave() {
  console.log('--- Baleadas War Stats: Static Data Builder ---\n');

  try {
    const token = await getApiToken();

    const warLogUrl = `${API_BASE}/clans/${CLAN_TAG}/riverracelog?limit=20`;
    const clanUrl = `${API_BASE}/clans/${CLAN_TAG}`;

    const headers = {
      'Authorization': `Bearer ${token}`,
      'Accept': 'application/json'
    };

    console.log('\nFetching war log...');
    const warRes = await fetch(warLogUrl, { headers });
    if (!warRes.ok) {
      throw new Error(`Warlog API Error ${warRes.status}: ${await warRes.text()}`);
    }
    const warData = await warRes.json();
    fs.writeFileSync(path.join(dataDir, 'warlog.json'), JSON.stringify(warData, null, 2));
    console.log('  Saved public/data/warlog.json');

    console.log('Fetching clan info...');
    const clanRes = await fetch(clanUrl, { headers });
    if (clanRes.ok) {
      const clanData = await clanRes.json();
      fs.writeFileSync(path.join(dataDir, 'clan.json'), JSON.stringify(clanData, null, 2));
      console.log('  Saved public/data/clan.json');
    } else {
      console.warn(`  Clan API returned status ${clanRes.status}`);
    }

    console.log('\nDone! Static data build complete.');
  } catch (err) {
    console.error('\nERROR:', err.message);
    process.exit(1);
  }
}

fetchAndSave();
